"""Rebuild a short call montage and write frame-accurate captions."""
from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import imageio_ffmpeg
from mutagen.mp3 import MP3

ff = Path(imageio_ffmpeg.get_ffmpeg_exe())
shutil.copy(ff, ff.with_name("ffmpeg.exe"))
os.environ["PATH"] = str(ff.parent) + os.pathsep + os.environ.get("PATH", "")
ffmpeg = str(ff.with_name("ffmpeg.exe"))

root = Path(__file__).resolve().parents[1]
aud_dir = root / "public" / "audio"
insp = root / "public" / "inspect"
insp.mkdir(parents=True, exist_ok=True)
src = aud_dir / "call_full.m4a"
out = aud_dir / "call_montage.mp3"

# Absolute windows on call_full.m4a (from earlier full-call Whisper)
# Kept short so montage fits Demo1 after the Maisa intro (~29s budget).
windows = [
    (0.0, 8.8),  # SILTA Thriver Care greeting
    (64.8, 71.2),  # clinician-look line (no diagnosis)
    (160.8, 174.6),  # consent question + patient yes + sending summary
]

# Captions timed relative to the concatenated montage timeline.
# start/end are seconds inside call_montage.mp3
# Timed from Whisper on the built montage (product names corrected for display)
caption_plan = [
    {
        "start": 0.0,
        "end": 8.0,
        "text": "Hello, this is SILTA from the Thriver Care cancer checkup service…",
    },
    {
        "start": 8.0,
        "end": 14.0,
        "text": "A painful lump that stayed about the same for a week is worth a clinician look.",
    },
    # 14–16s is a splice join — leave uncapped
    {
        "start": 16.0,
        "end": 21.0,
        "text": "Would it be all right if I share this checkup summary with your care team for human review only?",
    },
    {
        "start": 21.0,
        "end": 23.0,
        "text": "Yeah, that's fine.",
    },
    {
        "start": 23.0,
        "end": 28.0,
        "text": "Thank you. I am sending your checkup summary to your care team now.",
    },
]

filt = []
labels = []
for i, (st, en) in enumerate(windows):
    lab = f"a{i}"
    labels.append(f"[{lab}]")
    dur = en - st
    fade_out = max(0.12, dur - 0.25)
    filt.append(
        f"[0:a]atrim={st}:{en},asetpts=PTS-STARTPTS,"
        f"afade=t=in:st=0:d=0.06,afade=t=out:st={fade_out:.2f}:d=0.2[{lab}]"
    )
filt.append(
    "".join(labels)
    + f"concat=n={len(windows)}:v=0:a=1,loudnorm=I=-18:TP=-1.5:LRA=11[out]"
)
subprocess.check_call(
    [
        ffmpeg,
        "-y",
        "-i",
        str(src),
        "-filter_complex",
        ";".join(filt),
        "-map",
        "[out]",
        "-ar",
        "48000",
        str(out),
    ],
    stdout=subprocess.DEVNULL,
    stderr=subprocess.DEVNULL,
)

duration = float(MP3(out).info.length)
print(f"montage_duration={duration:.2f}")

# Snap caption ends to actual duration
cues = []
for c in caption_plan:
    start = max(0.0, min(c["start"], duration - 0.05))
    end = max(start + 0.2, min(c["end"], duration))
    cues.append({"startSec": round(start, 2), "endSec": round(end, 2), "text": c["text"]})

(insp / "montage_captions.json").write_text(
    json.dumps(
        {"duration": round(duration, 2), "windows": windows, "cues": cues},
        indent=2,
    ),
    encoding="utf-8",
)

fps = 30
lines = [
    "/* Auto-generated by scripts/rebuild_call_montage.py — do not edit by hand */",
    'import type {CaptionCue} from "../components/Captions";',
    "",
    f"export const CALL_MONTAGE_DURATION_SEC = {duration:.2f};",
    "",
    "export const CALL_CUES: CaptionCue[] = [",
]
for c in cues:
    start_f = int(round(c["startSec"] * fps))
    end_f = max(start_f + 1, int(round(c["endSec"] * fps)))
    text = c["text"].replace("\\", "\\\\").replace('"', '\\"')
    lines.append(f'  {{ start: {start_f}, end: {end_f}, text: "{text}" }},')
lines.append("];")
lines.append("")

ts_path = root / "src" / "data" / "callCaptions.ts"
ts_path.parent.mkdir(parents=True, exist_ok=True)
ts_path.write_text("\n".join(lines), encoding="utf-8")
print("wrote", ts_path)
for c in cues:
    print(f"{c['startSec']:6.2f}-{c['endSec']:6.2f}  {c['text']}")
